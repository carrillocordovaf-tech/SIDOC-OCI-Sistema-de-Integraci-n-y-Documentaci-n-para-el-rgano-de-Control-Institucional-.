-- Run once in Supabase SQL Editor (or apply with the Supabase migration tool).
-- This private schema is not an exposed browser Data API schema.
BEGIN;
CREATE SCHEMA IF NOT EXISTS sidoc;
REVOKE ALL ON SCHEMA sidoc FROM PUBLIC, anon, authenticated;

CREATE TABLE sidoc.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT UNIQUE NOT NULL,
 password TEXT NOT NULL,
 role TEXT NOT NULL CHECK (role IN ('admin','personal')),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
 auth_version INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE sidoc.expedients (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT UNIQUE NOT NULL, title TEXT NOT NULL,
 owner BIGINT NOT NULL REFERENCES sidoc.users(id),
 created TEXT NOT NULL DEFAULT to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE sidoc.documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title TEXT NOT NULL, filename TEXT NOT NULL, storage TEXT UNIQUE NOT NULL,
 owner BIGINT NOT NULL REFERENCES sidoc.users(id),
 created TEXT NOT NULL DEFAULT to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'),
 code TEXT NOT NULL DEFAULT '', kind TEXT NOT NULL DEFAULT 'Otro'
 CHECK(kind IN ('Informe','Oficio','Memorando','Acta','Otro')),
 unit TEXT NOT NULL DEFAULT '', folios INTEGER NOT NULL DEFAULT 0 CHECK(folios>=0),
 size BIGINT NOT NULL DEFAULT 0 CHECK(size>=0 AND size<=10485760),
 status TEXT NOT NULL DEFAULT 'Pendiente' CHECK(status IN ('Pendiente','En revisión','Archivado')),
 expedient_id BIGINT REFERENCES sidoc.expedients(id)
);
CREATE TABLE sidoc.favorites (
 user_id BIGINT REFERENCES sidoc.users(id),
 document_id BIGINT REFERENCES sidoc.documents(id) ON DELETE CASCADE,
 PRIMARY KEY(user_id,document_id)
);
CREATE TABLE sidoc.loans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_id BIGINT NOT NULL REFERENCES sidoc.documents(id) ON DELETE RESTRICT,
 borrower TEXT NOT NULL, due TEXT NOT NULL, returned TEXT,
 created TEXT NOT NULL DEFAULT to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS')
);
CREATE UNIQUE INDEX one_active_loan ON sidoc.loans(document_id) WHERE returned IS NULL;
CREATE TABLE sidoc.events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor BIGINT REFERENCES sidoc.users(id), description TEXT NOT NULL,
 created TEXT NOT NULL DEFAULT to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE sidoc.settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE sidoc.login_attempts (
 address TEXT NOT NULL,
 created TEXT NOT NULL DEFAULT to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE sidoc.pending_uploads (
 id TEXT PRIMARY KEY, owner BIGINT NOT NULL REFERENCES sidoc.users(id), storage TEXT UNIQUE NOT NULL,
 metadata TEXT NOT NULL, expires BIGINT NOT NULL,
 status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','processing','failed','complete')),
 document_id BIGINT REFERENCES sidoc.documents(id) ON DELETE SET NULL
);
CREATE TABLE sidoc.object_deletions (storage TEXT PRIMARY KEY);
CREATE INDEX documents_owner_created ON sidoc.documents(owner,created DESC);
CREATE INDEX documents_expedient ON sidoc.documents(expedient_id);
CREATE INDEX pending_uploads_expiry ON sidoc.pending_uploads(expires);
CREATE INDEX events_actor_created ON sidoc.events(actor,created DESC);
CREATE INDEX login_attempts_address_created ON sidoc.login_attempts(address,created);

ALTER TABLE sidoc.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.expedients ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.favorites ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.loans ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.login_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.pending_uploads ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.object_deletions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA sidoc FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA sidoc FROM PUBLIC, anon, authenticated;
COMMIT;
