BEGIN;
-- Se calcula para nuevas cargas; no modifica PDFs ni presupone hashes históricos.
ALTER TABLE sidoc.documents ADD COLUMN sha256 TEXT CHECK(sha256 IS NULL OR length(sha256)=64);
CREATE UNIQUE INDEX documents_owner_sha256 ON sidoc.documents(owner,sha256) WHERE sha256 IS NOT NULL;
CREATE TABLE sidoc.service_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL CHECK(length(trim(code)) BETWEEN 1 AND 80),
 subject TEXT NOT NULL CHECK(length(trim(subject)) BETWEEN 1 AND 200),
 requester TEXT NOT NULL CHECK(length(trim(requester)) BETWEEN 1 AND 200),
 owner BIGINT NOT NULL REFERENCES sidoc.users(id),
 creator BIGINT NOT NULL REFERENCES sidoc.users(id),
 received_at TEXT NOT NULL,
 deadline_days INTEGER NOT NULL CHECK(deadline_days BETWEEN 1 AND 3),
 due_at TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Registrado' CHECK(status IN ('Registrado','En trámite','Atendido','Archivado')),
 expedient_id BIGINT REFERENCES sidoc.expedients(id),
 source_document_id BIGINT REFERENCES sidoc.documents(id) ON DELETE RESTRICT,
 response_document_id BIGINT REFERENCES sidoc.documents(id) ON DELETE RESTRICT,
 response_note TEXT NOT NULL DEFAULT '',
 responded_at TEXT,
 version INTEGER NOT NULL DEFAULT 0,
 CHECK(status NOT IN ('Atendido','Archivado') OR (responded_at IS NOT NULL AND length(trim(response_note)) > 0))
);
CREATE UNIQUE INDEX service_requests_code ON sidoc.service_requests(lower(trim(code)));
CREATE INDEX service_requests_owner_due ON sidoc.service_requests(owner,due_at);
CREATE TABLE sidoc.request_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id BIGINT NOT NULL REFERENCES sidoc.service_requests(id) ON DELETE RESTRICT,
 actor BIGINT NOT NULL REFERENCES sidoc.users(id),
 description TEXT NOT NULL,
 created TEXT NOT NULL
);
CREATE INDEX request_events_request ON sidoc.request_events(request_id,id);
CREATE TABLE sidoc.archive_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 archive_item_id BIGINT NOT NULL REFERENCES sidoc.archive_items(id) ON DELETE RESTRICT,
 actor BIGINT NOT NULL REFERENCES sidoc.users(id),
 description TEXT NOT NULL,
 created TEXT NOT NULL
);
CREATE INDEX archive_events_item ON sidoc.archive_events(archive_item_id,id);
ALTER TABLE sidoc.archive_events ENABLE ROW LEVEL SECURITY;
CREATE UNIQUE INDEX archive_items_code_normalized ON sidoc.archive_items(lower(trim(inventory_code)));
CREATE UNIQUE INDEX physical_locations_code_normalized ON sidoc.physical_locations(lower(trim(code)));
ALTER TABLE sidoc.service_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.request_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA sidoc FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA sidoc FROM PUBLIC, anon, authenticated;
COMMIT;
