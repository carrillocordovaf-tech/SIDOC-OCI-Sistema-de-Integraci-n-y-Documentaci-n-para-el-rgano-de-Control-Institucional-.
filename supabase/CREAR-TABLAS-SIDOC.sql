CREATE TABLE sidoc.physical_locations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE CHECK(length(trim(code)) > 0),
 site TEXT NOT NULL CHECK(length(trim(site)) > 0),
 room TEXT NOT NULL CHECK(length(trim(room)) > 0),
 shelf TEXT NOT NULL DEFAULT '',
 shelf_level TEXT NOT NULL DEFAULT '',
 box TEXT NOT NULL DEFAULT '',
 folder TEXT NOT NULL DEFAULT '',
 notes TEXT NOT NULL DEFAULT '',
 active BOOLEAN NOT NULL DEFAULT TRUE
);

ALTER TABLE sidoc.documents ADD COLUMN document_type_id BIGINT REFERENCES sidoc.document_types(id);
ALTER TABLE sidoc.documents ADD COLUMN issued_on DATE;
ALTER TABLE sidoc.documents ADD COLUMN issuer TEXT NOT NULL DEFAULT '';
ALTER TABLE sidoc.documents ADD COLUMN recipient TEXT NOT NULL DEFAULT '';

-- One record per physical document or file, including material awaiting scanning.
CREATE TABLE sidoc.archive_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventory_code TEXT NOT NULL UNIQUE CHECK(length(trim(inventory_code)) > 0),
 title TEXT NOT NULL CHECK(length(trim(title)) > 0),
 record_type TEXT NOT NULL CHECK(record_type IN ('Documento','Expediente')),
 document_type_id BIGINT REFERENCES sidoc.document_types(id),
 original_number TEXT NOT NULL DEFAULT '',
 year_from SMALLINT NOT NULL CHECK(year_from BETWEEN 1800 AND 9999),
 year_to SMALLINT NOT NULL CHECK(year_to BETWEEN 1800 AND 9999 AND year_to >= year_from),
 issued_on DATE,
 producing_office TEXT NOT NULL DEFAULT '',
 expedient_id BIGINT REFERENCES sidoc.expedients(id),
 physical_location_id BIGINT NOT NULL REFERENCES sidoc.physical_locations(id),
 folio_from INTEGER CHECK(folio_from > 0),
 folio_to INTEGER CHECK(folio_to >= folio_from),
 conservation TEXT NOT NULL DEFAULT 'Por evaluar' CHECK(conservation IN ('Por evaluar','Bueno','Regular','Deteriorado')),
 digitization_status TEXT NOT NULL DEFAULT 'Pendiente' CHECK(digitization_status IN ('Pendiente','En proceso','Digitalizado parcial','Digitalizado','Revisado')),
 access_level TEXT NOT NULL DEFAULT 'Interno' CHECK(access_level IN ('Interno','Restringido','Público')),
 custodian BIGINT NOT NULL REFERENCES sidoc.users(id),
 notes TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(folio_to IS NULL OR folio_from IS NOT NULL)
);
-- Several PDFs may correspond to one physical file (volumes, parts, annexes).
CREATE TABLE sidoc.archive_item_documents (
 archive_item_id BIGINT NOT NULL REFERENCES sidoc.archive_items(id) ON DELETE CASCADE,
 document_id BIGINT NOT NULL REFERENCES sidoc.documents(id) ON DELETE RESTRICT,
 part_label TEXT NOT NULL DEFAULT '',
 PRIMARY KEY(archive_item_id,document_id)
);
CREATE INDEX archive_items_year ON sidoc.archive_items(year_from,year_to);
CREATE INDEX archive_items_location ON sidoc.archive_items(physical_location_id);
CREATE INDEX archive_items_expedient ON sidoc.archive_items(expedient_id);
CREATE INDEX archive_items_custodian ON sidoc.archive_items(custodian);
CREATE INDEX archive_item_documents_document ON sidoc.archive_item_documents(document_id);
ALTER TABLE sidoc.document_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.physical_locations ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.archive_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE sidoc.archive_item_documents ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA sidoc FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA sidoc FROM PUBLIC, anon, authenticated;

COMMIT;

SELECT table_name FROM information_schema.tables WHERE table_schema = 'sidoc' ORDER BY table_name;
