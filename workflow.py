"""Trámite OCI e inventario físico. Autorización siempre en el servidor."""
import csv
import io
import sqlite3
from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

import psycopg
from flask import abort, flash, g, redirect, render_template, request, send_file, url_for

LIMA = ZoneInfo('America/Lima')
UTC = ZoneInfo('UTC')
STATUSES = ('Registrado', 'En trámite', 'Atendido', 'Archivado')
DIGITAL = ('Pendiente', 'En proceso', 'Digitalizado parcial', 'Digitalizado', 'Revisado')



def now():
    return datetime.now(UTC)


def stamp(value):
    return value.astimezone(UTC).strftime('%Y-%m-%dT%H:%M:%S+00:00')


def deadline(received, days):
    """Plazo operativo de 24/48/72 horas, sin presumir una regla legal."""
    if days not in (1, 2, 3):
        raise ValueError('El plazo debe ser de 1 a 3 días calendario.')
    return received + timedelta(days=days)


def init_local(db):
    # Same schema as migrations 0003/0004, adapted only for SQLite identity types.
    from pathlib import Path
    for name in ('0003_archivo_historico.sql', '0004_tramite_oci.sql'):
        sentinel = 'archive_items' if name.startswith('0003') else 'service_requests'
        if db.execute("SELECT name FROM sqlite_master WHERE type='table' AND name=?", (sentinel,)).fetchone():
            continue
        source = (Path(__file__).parent / 'supabase' / 'migrations' / name).read_text()
        lines = []
        for line in source.splitlines():
            if line.strip().startswith(('ALTER TABLE sidoc.', 'REVOKE ')) and ('ROW LEVEL SECURITY' in line or line.strip().startswith('REVOKE ')):
                continue
            lines.append(line)
        sql = '\n'.join(lines).replace('sidoc.', '').replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'INTEGER PRIMARY KEY').replace('DEFAULT now()', 'DEFAULT CURRENT_TIMESTAMP')
        db.executescript(sql)



def workflow_available(connection, cloud):
    if isinstance(connection, sqlite3.Connection):
        return bool(connection.execute("SELECT name FROM sqlite_master WHERE type='table' AND name=?", ('service_requests',)).fetchone())
    return bool(connection.execute('SELECT to_regclass(?) AS ready', ('sidoc.service_requests',)).fetchone()['ready'])


def configure_workflow(app, db, protected, audit, cloud):
    def ready():
        if cloud:
            found = db().execute('SELECT to_regclass(?) AS archive, to_regclass(?) AS requests',
                                 ('sidoc.archive_items', 'sidoc.service_requests')).fetchone()
            if not found['archive'] or not found['requests']:
                return False
        return True

    def require_schema():
        if not ready():
            return render_template('workflow_missing.html', section='requests'), 503

    def admin():
        if g.user['role'] != 'admin':
            abort(403)

    def text(name, maximum, required=True):
        value = request.form.get(name, '').strip()
        if (required and not value) or len(value) > maximum:
            raise ValueError('Revisa el campo ' + name + '.')
        return value

    def owner_scope(alias):
        return ('1=1', []) if g.user['role'] == 'admin' else (alias + '.owner=?', [g.user['id']])

    def visible_doc(doc_id):
        row = db().execute('SELECT * FROM documents WHERE id=?', (doc_id,)).fetchone()
        if not row or (g.user['role'] != 'admin' and row['owner'] != g.user['id']):
            abort(403)
        return row

    def reference(name, table):
        raw = request.form.get(name, '').strip()
        if not raw:
            return None
        try:
            key = int(raw)
        except ValueError:
            raise ValueError('Selecciona una referencia válida.')
        row = db().execute(f'SELECT * FROM {table} WHERE id=?', (key,)).fetchone()
        if not row:
            raise ValueError('La referencia seleccionada no existe.')
        if table == 'documents':
            visible_doc(key)
        elif table == 'expedients' and g.user['role'] != 'admin' and row['owner'] != g.user['id']:
            abort(403)
        elif table == 'users' and not row['active']:
            raise ValueError('El responsable debe tener una cuenta activa.')
        return key

    def choices():
        where, params = owner_scope('d')
        docs = db().execute(f'SELECT d.id,d.code,d.title FROM documents d WHERE {where} ORDER BY d.id DESC', params).fetchall()
        where, params = owner_scope('e')
        exps = db().execute(f'SELECT e.id,e.code,e.title FROM expedients e WHERE {where} ORDER BY e.id DESC', params).fetchall()
        users = db().execute('SELECT id,username FROM users WHERE active=1 ORDER BY username').fetchall() if g.user['role'] == 'admin' else []
        return dict(documents=docs, expedients=exps, owners=users)

    def scoped_request(key):
        row = db().execute('SELECT r.*,u.username FROM service_requests r JOIN users u ON u.id=r.owner WHERE r.id=?', (key,)).fetchone()
        if not row:
            abort(404)
        if g.user['role'] != 'admin' and row['owner'] != g.user['id']:
            abort(403)
        return row

    def request_event(key, description):
        db().execute('INSERT INTO request_events(request_id,actor,description,created) VALUES (?,?,?,?)',
                     (key, g.user['id'], description, stamp(now())))
        audit(f'Requerimiento #{key}: {description}')

    def decorate(row):
        row = dict(row)
        due = datetime.fromisoformat(row['due_at'])
        row['due_display'] = due.astimezone(LIMA).strftime('%d/%m/%Y %H:%M')
        row['received_display'] = datetime.fromisoformat(row['received_at']).astimezone(LIMA).strftime('%d/%m/%Y %H:%M')
        if row['responded_at']:
            response = datetime.fromisoformat(row['responded_at'])
            row['deadline_label'] = 'Atendido en plazo' if response <= due else 'Atendido fuera de plazo'
            row['response_hours'] = round((response - datetime.fromisoformat(row['received_at'])).total_seconds()/3600, 1)
        else:
            remaining = (due-now()).total_seconds()/3600
            row['deadline_label'] = 'Vencido' if remaining < 0 else 'Vence en 24 h' if remaining <= 24 else 'En plazo'
        return row

    @app.route('/requests', methods=['GET', 'POST'])
    @protected()
    def service_requests():
        missing = require_schema()
        if missing:
            return missing
        if request.method == 'POST':
            admin()
            try:
                code, subject, requester = text('code', 80).upper(), text('subject', 200), text('requester', 200)
                owner = reference('owner', 'users')
                if not owner:
                    raise ValueError('Selecciona un responsable.')
                received = datetime.fromisoformat(text('received_at', 32)).replace(tzinfo=LIMA).astimezone(UTC)
                if received > now():
                    raise ValueError('La recepción no puede estar en el futuro.')
                days = int(request.form.get('deadline_days', ''))
                due = deadline(received, days)
                exp, source = reference('expedient_id', 'expedients'), reference('source_document_id', 'documents')
                row = db().execute('''INSERT INTO service_requests(code,subject,requester,owner,creator,received_at,deadline_days,due_at,expedient_id,source_document_id)
                    VALUES (?,?,?,?,?,?,?,?,?,?) RETURNING id''',
                    (code, subject, requester, owner, g.user['id'], stamp(received), days, stamp(due), exp, source)).fetchone()
                request_event(row['id'], f'Registrado con responsable #{owner}; plazo {days} día(s) calendario.')
                db().commit()
                return redirect(url_for('service_request_detail', key=row['id']))
            except (ValueError, OverflowError):
                db().rollback()
                flash('Revisa los datos: recepción válida, responsable activo y plazo de 1 a 3 días.')
            except (sqlite3.IntegrityError, psycopg.IntegrityError):
                db().rollback()
                flash('El código del requerimiento ya está registrado o sus referencias no son válidas.')
            return redirect(url_for('service_requests'))
        where, params = owner_scope('r')
        query = request.args.get('q', '').strip()[:200].lower()
        if query:
            where += ' AND (lower(r.code) LIKE ? OR lower(r.subject) LIKE ? OR lower(r.requester) LIKE ?)'
            params += ['%'+query+'%']*3
        status = request.args.get('status', '')
        if status in STATUSES:
            where += ' AND r.status=?'
            params.append(status)
        rows = [decorate(r) for r in db().execute(f'''SELECT r.*,u.username FROM service_requests r
            JOIN users u ON u.id=r.owner WHERE {where} ORDER BY CASE WHEN r.status IN ('Registrado','En trámite') THEN 0 ELSE 1 END,r.due_at,r.id''', params)]
        totals = {label: sum(r['deadline_label'] == label for r in rows) for label in ('Vencido', 'Vence en 24 h', 'En plazo', 'Atendido en plazo', 'Atendido fuera de plazo')}
        completed = [r['response_hours'] for r in rows if 'response_hours' in r]
        return render_template('requests.html', section='requests', rows=rows, totals=totals, statuses=STATUSES,
                               mean_hours=round(sum(completed)/len(completed), 1) if completed else None,
                               received_default=now().astimezone(LIMA).strftime('%Y-%m-%dT%H:%M'), **choices())

    @app.route('/requests/<int:key>', methods=['GET', 'POST'])
    @protected()
    def service_request_detail(key):
        missing = require_schema()
        if missing:
            return missing
        row = scoped_request(key)
        if request.method == 'POST':
            try:
                version = int(request.form.get('version', '-1'))
                note = text('note', 2000)
                action = request.form.get('action')
                if action == 'assign':
                    admin()
                    owner = reference('owner', 'users')
                    if not owner or row['status'] in ('Atendido', 'Archivado'):
                        raise ValueError()
                    changed = db().execute('UPDATE service_requests SET owner=?,version=version+1 WHERE id=? AND version=? RETURNING id',
                                            (owner, key, version)).fetchone()
                    description = f'Derivado de responsable #{row["owner"]} a #{owner}. {note}'
                else:
                    target = request.form.get('status', '')
                    allowed = {'Registrado': ('En trámite',), 'En trámite': ('Atendido',), 'Atendido': ('Archivado',), 'Archivado': ()}
                    if target not in allowed[row['status']] or (target == 'Archivado' and g.user['role'] != 'admin'):
                        raise ValueError()
                    response_doc = reference('response_document_id', 'documents') if target == 'Atendido' else row['response_document_id']
                    responded = stamp(now()) if target == 'Atendido' else row['responded_at']
                    response_note = note if target == 'Atendido' else row['response_note']
                    changed = db().execute('''UPDATE service_requests SET status=?,responded_at=?,response_note=?,response_document_id=?,version=version+1
                        WHERE id=? AND version=? RETURNING id''', (target, responded, response_note, response_doc, key, version)).fetchone()
                    description = f'{row["status"]} → {target}. {note}'
                if not changed:
                    db().rollback()
                    flash('Otro usuario actualizó este requerimiento. Revisa el historial antes de continuar.')
                else:
                    request_event(key, description)
                    db().commit()
                    flash('Seguimiento actualizado.')
            except (ValueError, sqlite3.IntegrityError, psycopg.IntegrityError):
                db().rollback()
                flash('Revisa la transición, la nota y las referencias seleccionadas.')
            return redirect(url_for('service_request_detail', key=key))
        events = db().execute('''SELECT e.*,u.username FROM request_events e JOIN users u ON u.id=e.actor
            WHERE e.request_id=? ORDER BY e.id''', (key,)).fetchall()
        row = decorate(row)
        # A linked document never bypasses its own download authorization.
        row['source_visible'] = bool(row['source_document_id'] and db().execute(
            'SELECT id FROM documents WHERE id=?' + ('' if g.user['role'] == 'admin' else ' AND owner=?'),
            (row['source_document_id'],) if g.user['role'] == 'admin' else (row['source_document_id'], g.user['id'])).fetchone())
        row['response_visible'] = bool(row['response_document_id'] and db().execute(
            'SELECT id FROM documents WHERE id=?' + ('' if g.user['role'] == 'admin' else ' AND owner=?'),
            (row['response_document_id'],) if g.user['role'] == 'admin' else (row['response_document_id'], g.user['id'])).fetchone())
        return render_template('request_detail.html', section='requests', row=row, events=events, **choices())

    @app.get('/requests/export')
    @protected()
    def requests_export():
        missing = require_schema()
        if missing:
            return missing
        where, params = owner_scope('r')
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(['Código','Asunto','Solicitante','Responsable','Estado','Recepción Lima','Vence Lima','Plazo','Horas hasta atención','Respuesta'])
        for raw in db().execute(f"SELECT r.*,u.username FROM service_requests r JOIN users u ON u.id=r.owner WHERE {where} ORDER BY r.id", params):
            r = decorate(raw)
            cells = [r['code'],r['subject'],r['requester'],r['username'],r['status'],r['received_display'],r['due_display'],r['deadline_label'],r.get('response_hours',''),r['response_note']]
            writer.writerow(["'"+str(c) if str(c).lstrip().startswith(('=','+','-','@')) else c for c in cells])
        audit('Exportó seguimiento de requerimientos de su ámbito')
        db().commit()
        return send_file(io.BytesIO(output.getvalue().encode('utf-8-sig')), mimetype='text/csv', as_attachment=True, download_name='SIDOC-requerimientos.csv')

    def archive_event(key, description):
        db().execute('INSERT INTO archive_events(archive_item_id,actor,description,created) VALUES (?,?,?,?)',
                     (key,g.user['id'],description,stamp(now())))
        audit(description)

    def inventory_item(key):
        row = db().execute('SELECT a.*,u.username FROM archive_items a JOIN users u ON u.id=a.custodian WHERE a.id=?', (key,)).fetchone()
        if not row:
            abort(404)
        if g.user['role'] != 'admin' and row['custodian'] != g.user['id']:
            abort(403)
        return row

    @app.route('/inventory', methods=['GET', 'POST'])
    @protected()
    def inventory():
        missing = require_schema()
        if missing:
            return missing
        if request.method == 'POST':
            admin()
            try:
                if request.form.get('action') == 'location':
                    values = [text('code', 80).upper(), text('site', 200), text('room', 200)]
                    values += [text(field, 100, False) for field in ('shelf', 'shelf_level', 'box', 'folder')]
                    db().execute('INSERT INTO physical_locations(code,site,room,shelf,shelf_level,box,folder) VALUES (?,?,?,?,?,?,?)', values)
                    audit(f'Registró ubicación física: {values[0]}')
                    destination = url_for('inventory')
                else:
                    code, title = text('inventory_code', 80).upper(), text('title', 200)
                    record_type = request.form.get('record_type', '')
                    y1, y2 = int(request.form.get('year_from', '')), int(request.form.get('year_to', ''))
                    if record_type not in ('Documento', 'Expediente') or not 1800 <= y1 <= y2 <= now().astimezone(LIMA).year:
                        raise ValueError()
                    location = reference('physical_location_id', 'physical_locations')
                    owner = reference('custodian', 'users')
                    kind = reference('document_type_id', 'document_types')
                    exp = reference('expedient_id', 'expedients')
                    if not location or not owner:
                        raise ValueError()
                    original, office = text('original_number', 200, False), text('producing_office', 200, False)
                    first = int(request.form['folio_from']) if request.form.get('folio_from') else None
                    last = int(request.form['folio_to']) if request.form.get('folio_to') else None
                    if (first is not None and first < 1) or (last is not None and (first is None or last < first)):
                        raise ValueError()
                    conservation = request.form.get('conservation', 'Por evaluar')
                    if conservation not in ('Por evaluar', 'Bueno', 'Regular', 'Deteriorado'):
                        raise ValueError()
                    result = db().execute('''INSERT INTO archive_items(inventory_code,title,record_type,document_type_id,original_number,year_from,year_to,
                        producing_office,expedient_id,physical_location_id,custodian,conservation,notes,folio_from,folio_to)
                        VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?) RETURNING id''',
                        (code, title, record_type, kind, original, y1, y2, office, exp, location, owner, conservation, text('notes', 2000, False), first, last)).fetchone()
                    archive_event(result['id'], f'Inventarió original físico {code} en ubicación #{location}')
                    destination = url_for('inventory_detail', key=result['id'])
                db().commit()
                return redirect(destination)
            except (ValueError, sqlite3.IntegrityError, psycopg.IntegrityError):
                db().rollback()
                flash('Revisa años, referencias y campos obligatorios. Los códigos deben ser únicos.')
                return redirect(url_for('inventory'))
        where, params = ('1=1', []) if g.user['role'] == 'admin' else ('a.custodian=?', [g.user['id']])
        q = request.args.get('q', '').strip()[:200].lower()
        if q:
            where += ''' AND (lower(a.inventory_code) LIKE ? OR lower(a.title) LIKE ? OR lower(a.original_number) LIKE ?
                OR lower(l.code) LIKE ? OR lower(l.box) LIKE ? OR lower(l.folder) LIKE ?)'''
            params += ['%'+q+'%']*6
        year = request.args.get('year', type=int)
        if year:
            where += ' AND a.year_from<=? AND a.year_to>=?'
            params += [year, year]
        state = request.args.get('digitization_status', '')
        if state in DIGITAL:
            where += ' AND a.digitization_status=?'
            params.append(state)
        rows = db().execute(f'''SELECT a.*,l.code AS location_code,l.site,l.room,l.shelf,l.shelf_level,l.box,l.folder,
            u.username,t.name AS type_name FROM archive_items a JOIN physical_locations l ON l.id=a.physical_location_id
            JOIN users u ON u.id=a.custodian LEFT JOIN document_types t ON t.id=a.document_type_id
            WHERE {where} ORDER BY a.year_from,a.inventory_code''', params).fetchall()
        return render_template('inventory.html', section='inventory', rows=rows, digital_states=DIGITAL,
                               locations=db().execute('SELECT * FROM physical_locations WHERE active=TRUE ORDER BY code').fetchall(),
                               document_types=db().execute('SELECT * FROM document_types WHERE active=TRUE ORDER BY name').fetchall(),
                               current_year=now().astimezone(LIMA).year, **choices())

    @app.route('/inventory/<int:key>', methods=['GET', 'POST'])
    @protected()
    def inventory_detail(key):
        missing = require_schema()
        if missing:
            return missing
        row = inventory_item(key)
        if request.method == 'POST':
            admin()
            try:
                if request.form.get('action') == 'link':
                    doc = reference('document_id', 'documents')
                    if not doc:
                        raise ValueError()
                    db().execute('INSERT INTO archive_item_documents(archive_item_id,document_id,part_label) VALUES (?,?,?)',
                                 (key, doc, text('part_label', 200)))
                    archive_event(key, f'Inventario {row["inventory_code"]}: vinculó PDF #{doc}')
                else:
                    state = request.form.get('digitization_status', '')
                    loc = reference('physical_location_id', 'physical_locations')
                    note = text('note', 2000)
                    if state not in DIGITAL or not loc:
                        raise ValueError()
                    if state in ('Digitalizado parcial', 'Digitalizado', 'Revisado') and not db().execute(
                        'SELECT 1 FROM archive_item_documents WHERE archive_item_id=?', (key,)).fetchone():
                        raise ValueError()
                    changed = db().execute('UPDATE archive_items SET digitization_status=?,physical_location_id=? WHERE id=? AND digitization_status=? AND physical_location_id=? RETURNING id', (state, loc, key, row['digitization_status'], row['physical_location_id'])).fetchone()
                    if not changed:
                        raise ValueError('Otro administrador actualizó este registro; recarga antes de continuar.')
                    archive_event(key, f'Inventario {row["inventory_code"]}: {row["digitization_status"]} → {state}; ubicación #{row["physical_location_id"]} → #{loc}. {note}')
                db().commit()
                flash('Inventario actualizado.')
            except (ValueError, sqlite3.IntegrityError, psycopg.IntegrityError):
                db().rollback()
                flash('Revisa los datos. Para marcar digitalizado o revisado debes vincular al menos un PDF; no se permiten vínculos duplicados.')
            return redirect(url_for('inventory_detail', key=key))
        where = '' if g.user['role'] == 'admin' else ' AND d.owner=?'
        params = [key] if not where else [key, g.user['id']]
        links = db().execute('''SELECT d.id,d.title,d.code,v.part_label FROM archive_item_documents v
            JOIN documents d ON d.id=v.document_id WHERE v.archive_item_id=?''' + where + ' ORDER BY d.id', params).fetchall()
        location = db().execute('SELECT * FROM physical_locations WHERE id=?', (row['physical_location_id'],)).fetchone()
        events = db().execute('SELECT e.*,u.username FROM archive_events e JOIN users u ON u.id=e.actor WHERE e.archive_item_id=? ORDER BY e.id', (key,)).fetchall()
        return render_template('inventory_detail.html', section='inventory', row=row, links=links, location=location, events=events,
                               locations=db().execute('SELECT * FROM physical_locations WHERE active=TRUE ORDER BY code').fetchall(),
                               digital_states=DIGITAL, **choices())
